const ESCAPED = Object.keys(NEXUS_TERMS)
  .sort((a, b) => b.length - a.length)
  .map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));

const PATTERN = new RegExp(`(?<![\\w@.])(${ESCAPED.join("|")})(?![\\w])`, "g");

/**
 * Replace CVS Health / healthcare wording with its Nexus equivalent.
 * Whole-passage rewrites win over the word-by-word map.
 */
export function swapTerms(text: string): string {
  if (!text) return text;
  const passage = swapPassage(text);
  if (passage !== null) {
    const lead = text.match(/^\s*/)?.[0] ?? "";
    const trail = text.match(/\s*$/)?.[0] ?? "";
    return `${lead}${passage}${trail}`;
  }
  return text.replace(PATTERN, (m) => NEXUS_TERMS[m] ?? m);
}

