const ESCAPED = Object.keys(RATHBONES_TERMS)
  .sort((a, b) => b.length - a.length)
  .map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));

const PATTERN = new RegExp(`(?<![\\w@.])(${ESCAPED.join("|")})(?![\\w])`, "g");

export function swapRathbonesTerms(text: string): string {
  if (!text) return text;
  return text.replace(PATTERN, (m) => RATHBONES_TERMS[m] ?? m);
}

